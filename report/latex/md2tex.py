    ("(Chen and Yang, Stanford, 2020)", "chen2020posetrainer"),
    ("(Parmar, Gharat and Rhodin, ECCV 2022)", "parmar2022fitnessaqa"),
    ("(Cook, Burton and Hoogenboom 2006)", "cook2006fms"),
    (u"(Eimiller et al., 2025; Rodríguez-Perea et al., 2025)", "eimiller2025plank,rodriguezperea2025plank"),
    ("(Cook, Burton, Hoogenboom 2006)", "cook2006fms"),
